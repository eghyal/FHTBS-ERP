/**
 * Replicates a single ERP record to Supabase Cloud PostgreSQL (`public.erp_sync_records`).
 */
export async function replicateToPostgres(
  collectionName: string,
  docId: string,
  data: any,
): Promise<boolean> {
  if (!docId || !collectionName) return false;

  const syncedAtIso = new Date().toISOString();
  let sanitizedPayload: any = {};
  try {
    sanitizedPayload = JSON.parse(JSON.stringify(data ?? {}));
  } catch {
    sanitizedPayload = { raw: String(data) };
  }

  try {
    // When erp_sync_records is locked to service_role and SUPABASE_SERVICE_ROLE_KEY is not set,
    // use the direct PostgreSQL pooler connection first to bypass PostgREST anon restrictions cleanly.
    if (!SUPABASE_SERVICE_ROLE_KEY && isDirectPgConnected()) {
      await pgQuery(
        `INSERT INTO public.erp_sync_records (collection_name, record_id, payload, synced_at)
         VALUES ($1, $2, $3::jsonb, NOW())
         ON CONFLICT (collection_name, record_id)
         DO UPDATE SET payload = EXCLUDED.payload, synced_at = NOW()`,
        [collectionName, String(docId), JSON.stringify(sanitizedPayload)],
      );
      totalReplicatedRecords++;
      totalSupabaseSynced++;
      lastReplicatedAt = syncedAtIso;
      lastSupabaseSyncedAt = syncedAtIso;
      lastSupabaseError = null;
      lastReplicationError = null;
      return true;
    }

    const { error } = await supabaseServerClient.from("erp_sync_records").upsert(
      {
        collection_name: collectionName,
        record_id: String(docId),
        payload: sanitizedPayload,
        synced_at: syncedAtIso,
      },
      { onConflict: "collection_name,record_id" },
    );

    if (!error) {
      totalReplicatedRecords++;
      totalSupabaseSynced++;
      lastReplicatedAt = syncedAtIso;
      lastSupabaseSyncedAt = syncedAtIso;
      lastSupabaseError = null;
      lastReplicationError = null;
      return true;
    }

    // Fallback to direct pgPool if connected and REST returned an error
    if (isDirectPgConnected()) {
      await pgQuery(
        `INSERT INTO public.erp_sync_records (collection_name, record_id, payload, synced_at)
         VALUES ($1, $2, $3::jsonb, NOW())
         ON CONFLICT (collection_name, record_id)
         DO UPDATE SET payload = EXCLUDED.payload, synced_at = NOW()`,
        [collectionName, String(docId), JSON.stringify(sanitizedPayload)],
      );
      totalReplicatedRecords++;
      totalSupabaseSynced++;
      lastReplicatedAt = syncedAtIso;
      lastSupabaseSyncedAt = syncedAtIso;
      lastSupabaseError = null;
      lastReplicationError = null;
      return true;
    }

    lastSupabaseError = error.message;
    lastReplicationError = error.message;
    return false;
  } catch (err: any) {
    const msg = err?.message || String(err);
    lastSupabaseError = msg;
    lastReplicationError = msg;
    return false;
  }
}

/**
 * High-throughput batch replication of multiple records for a collection into Supabase `public.erp_sync_records`.
 */
export async function batchReplicateToPostgres(
  collectionName: string,
  items: { id: string; data: any }[],
  checksum?: string,
): Promise<number> {
  if (!collectionName || !items || items.length === 0) return 0;

  const syncedAtIso = new Date().toISOString();
  const CHUNK_SIZE = 250;
  let syncedCount = 0;

  for (let i = 0; i < items.length; i += CHUNK_SIZE) {
    const chunk = items.slice(i, i + CHUNK_SIZE);
    const payloadChunk = chunk.map((item) => {
      let cleanData: any = {};
      try {
        cleanData = JSON.parse(JSON.stringify(item.data ?? {}));
      } catch {
        cleanData = { raw: String(item.data) };
      }
      return {
        collection_name: collectionName,
        record_id: String(item.id),
        payload: cleanData,
        checksum: checksum || null,
        synced_at: syncedAtIso,
      };
    });

    if (!SUPABASE_SERVICE_ROLE_KEY && isDirectPgConnected()) {
      for (const row of payloadChunk) {
        await pgQuery(
          `INSERT INTO public.erp_sync_records (collection_name, record_id, payload, checksum, synced_at)
           VALUES ($1, $2, $3::jsonb, $4, NOW())
           ON CONFLICT (collection_name, record_id)
           DO UPDATE SET payload = EXCLUDED.payload, checksum = EXCLUDED.checksum, synced_at = NOW()`,
          [
            row.collection_name,
            row.record_id,
            JSON.stringify(row.payload),
            row.checksum,
          ],
        );
      }
    } else {
      const { error } = await supabaseServerClient
        .from("erp_sync_records")
        .upsert(payloadChunk, { onConflict: "collection_name,record_id" });

      if (error) {
        if (isDirectPgConnected()) {
          for (const row of payloadChunk) {
            await pgQuery(
              `INSERT INTO public.erp_sync_records (collection_name, record_id, payload, checksum, synced_at)
               VALUES ($1, $2, $3::jsonb, $4, NOW())
               ON CONFLICT (collection_name, record_id)
               DO UPDATE SET payload = EXCLUDED.payload, checksum = EXCLUDED.checksum, synced_at = NOW()`,
              [
                row.collection_name,
                row.record_id,
                JSON.stringify(row.payload),
                row.checksum,
              ],
            );
          }
        } else {
          lastSupabaseError = error.message;
          lastReplicationError = error.message;
          throw new Error(
            `Supabase batch upsert failed on ${collectionName}: ${error.message}`,
          );
        }
      }
    }

    syncedCount += chunk.length;
  }

  totalReplicatedRecords += syncedCount;
  totalSupabaseSynced += syncedCount;
  lastReplicatedAt = syncedAtIso;
  lastSupabaseSyncedAt = syncedAtIso;
  lastSupabaseError = null;
  lastReplicationError = null;

  return syncedCount;
}

/**
 * Deletes a replicated record from Supabase `public.erp_sync_records`.
 */
export async function deleteFromPostgres(
  collectionName: string,
  docId: string,
): Promise<boolean> {
  if (!docId || !collectionName) return false;

  try {
    if (!SUPABASE_SERVICE_ROLE_KEY && isDirectPgConnected()) {
      await pgQuery(
        `DELETE FROM public.erp_sync_records WHERE collection_name = $1 AND record_id = $2`,
        [collectionName, String(docId)],
      );
      lastSupabaseSyncedAt = new Date().toISOString();
      return true;
    }

    const { error } = await supabaseServerClient
      .from("erp_sync_records")
      .delete()
      .eq("collection_name", collectionName)
      .eq("record_id", String(docId));

    if (!error) {
      lastSupabaseSyncedAt = new Date().toISOString();
      return true;
    }

    if (isDirectPgConnected()) {
      await pgQuery(
        `DELETE FROM public.erp_sync_records WHERE collection_name = $1 AND record_id = $2`,
        [collectionName, String(docId)],
      );
      return true;
    }
    lastSupabaseError = error.message;
    return false;
  } catch (err: any) {
    lastReplicationError = err?.message || String(err);
    return false;
  }
}

/**
 * Clears all or selected ERP collections from Supabase `public.erp_sync_records` (used by Admin Reset).
 */
export async function clearSupabaseErpSyncRecords(
  collections?: string[],
): Promise<{ deletedCollections: number; error?: string }> {
  try {
    if (!SUPABASE_SERVICE_ROLE_KEY && isDirectPgConnected()) {
      if (collections && collections.length > 0) {
        await pgQuery(
          `DELETE FROM public.erp_sync_records WHERE collection_name = ANY($1::text[])`,
          [collections],
        );
        return { deletedCollections: collections.length };
      } else {
        await pgQuery(`DELETE FROM public.erp_sync_records`);
        return { deletedCollections: 1 };
      }
    }

    if (collections && collections.length > 0) {
      const { error } = await supabaseServerClient
        .from("erp_sync_records")
        .delete()
        .in("collection_name", collections);
      if (error) {
        if (isDirectPgConnected()) {
          await pgQuery(
            `DELETE FROM public.erp_sync_records WHERE collection_name = ANY($1::text[])`,
            [collections],
          );
          return { deletedCollections: collections.length };
        }
        return { deletedCollections: 0, error: error.message };
      }
      return { deletedCollections: collections.length };
    } else {
      const { error } = await supabaseServerClient
        .from("erp_sync_records")
        .delete()
        .neq("collection_name", "__never_match__");
      if (error) {
        if (isDirectPgConnected()) {
          await pgQuery(`DELETE FROM public.erp_sync_records`);
          return { deletedCollections: 1 };
        }
        return { deletedCollections: 0, error: error.message };
      }
      return { deletedCollections: 1 };
    }
  } catch (err: any) {
    return {
      deletedCollections: 0,
      error: err?.message || String(err),
    };
  }
}

/**
 * Helper to apply inbound records from PostgreSQL Primary SSOT into the local SQLite WAL Secondary Cache
 * with CDC triggers suppressed so inbound SSOT updates never echo back out to the outbox.
 */
function applyInboundPostgresRecordsToSqliteWal(
  records: Array<{
    collection_name: string;
    record_id: string;
    payload: any;
    synced_at?: string;
  }>,
): {
  totalRestoredRows: number;
  details: Array<{ table: string; restored: number }>;
  maxSyncedAt: string | null;
} {
  const byTable = new Map<string, any[]>();
  let maxSyncedAt: string | null = null;

  for (const row of records) {
    if (row.synced_at && (!maxSyncedAt || row.synced_at > maxSyncedAt)) {
      maxSyncedAt = row.synced_at;
    }
    if (!row.collection_name || !row.payload) continue;
    const list = byTable.get(row.collection_name) || [];
    list.push(row.payload);
    byTable.set(row.collection_name, list);
  }

  const details: Array<{ table: string; restored: number }> = [];
  let totalRestoredRows = 0;

  // Suppress local SQLite CDC triggers and foreign keys during inbound SSOT cache hydration
  sqliteDb.pragma("foreign_keys = OFF");
  setCdcTriggerSuppression(true, sqliteDb);
  try {
    for (const [tableName, payloads] of byTable.entries()) {
      if (!/^[a-zA-Z0-9_]+$/.test(tableName)) continue;

      const tableCheck = sqliteDb
        .prepare(
          "SELECT name FROM sqlite_master WHERE type='table' AND name = ?",
        )
        .get(tableName) as { name: string } | undefined;

      if (!tableCheck) continue;

      const tableInfo = sqliteDb
        .prepare(`PRAGMA table_info(${tableName})`)
        .all() as Array<{ name: string; pk: number }>;
      const validColumns = new Set(tableInfo.map((c) => c.name));
      if (validColumns.size === 0) continue;

      const pkCol =
        tableInfo.find((c) => c.pk === 1)?.name ||
        (validColumns.has("id")
          ? "id"
          : validColumns.has("key")
            ? "key"
            : validColumns.has("section_key")
              ? "section_key"
              : null);

      let tableRestoredCount = 0;

      const restoreTableTx = sqliteDb.transaction((rows: any[]) => {
        for (const rawItem of rows) {
          if (!rawItem || typeof rawItem !== "object") continue;
          try {
            let item = rawItem;
            // Merge with existing local row if payload is a partial update
            if (pkCol && rawItem[pkCol] !== undefined && rawItem[pkCol] !== null) {
              const existing = sqliteDb
                .prepare(`SELECT * FROM "${tableName}" WHERE "${pkCol}" = ?`)
                .get(rawItem[pkCol]) as Record<string, any> | undefined;
              if (existing && typeof existing === "object") {
                item = { ...existing, ...rawItem };
              }
            }

            const cols = Object.keys(item).filter((k) => validColumns.has(k));
            if (cols.length === 0) continue;

            const placeholders = cols.map(() => "?").join(", ");
            const values = cols.map((col) => {
              const val = item[col];
              if (val === undefined || val === null) return null;
              if (typeof val === "boolean") return val ? 1 : 0;
              if (typeof val === "object") return JSON.stringify(val);
              return val;
            });

            const sql = `INSERT OR REPLACE INTO "${tableName}" (${cols.map((c) => `"${c}"`).join(", ")}) VALUES (${placeholders})`;
            sqliteDb.prepare(sql).run(...values);
            tableRestoredCount++;
          } catch {
            // Skip malformed legacy partial record without aborting other records
          }
        }
      });

      restoreTableTx(payloads);
      if (tableRestoredCount > 0) {
        details.push({ table: tableName, restored: tableRestoredCount });
        totalRestoredRows += tableRestoredCount;
      }
    }
  } finally {
    setCdcTriggerSuppression(false, sqliteDb);
    sqliteDb.pragma("foreign_keys = ON");
  }

  if (maxSyncedAt) {
    setHybridSyncWatermark(maxSyncedAt, sqliteDb);
  }

  return { totalRestoredRows, details, maxSyncedAt };
}

/**
 * Rehydrates (pulls & restores) records from PostgreSQL Primary SSOT (`public.erp_sync_records`)
 * into the local SQLite WAL Secondary Cache.
 */
export async function rehydrateSqliteFromSupabase(
  targetTable?: string,
): Promise<{
  success: boolean;
  totalRestoredRows: number;
  tablesRestored: number;
  details: Array<{ table: string; restored: number }>;
  error?: string;
}> {
  try {
    const allRecords: Array<{
      collection_name: string;
      record_id: string;
      payload: any;
      synced_at?: string;
    }> = [];

    const PAGE_SIZE = 1000;
    let from = 0;
    let usedDirectFallback = !SUPABASE_SERVICE_ROLE_KEY && isDirectPgConnected();

    if (!usedDirectFallback) {
      while (true) {
        let query = supabaseServerClient
          .from("erp_sync_records")
          .select("collection_name, record_id, payload, synced_at")
          .order("collection_name", { ascending: true })
          .range(from, from + PAGE_SIZE - 1);

        if (targetTable) {
          query = query.eq("collection_name", targetTable);
        }

        const { data, error } = await query;
        if (error) {
          if (isDirectPgConnected()) {
            usedDirectFallback = true;
            break;
          }
          return {
            success: false,
            totalRestoredRows: 0,
            tablesRestored: 0,
            details: [],
            error: error.message,
          };
        }

        if (!data || data.length === 0) break;
        allRecords.push(...data);
        if (data.length < PAGE_SIZE) break;
        from += PAGE_SIZE;
      }
    }

    if (usedDirectFallback && isDirectPgConnected()) {
      const pgRes = targetTable
        ? await pgQuery<{
            collection_name: string;
            record_id: string;
            payload: any;
            synced_at?: string;
          }>(
            `SELECT collection_name, record_id, payload, synced_at::text as synced_at FROM public.erp_sync_records WHERE collection_name = $1 ORDER BY collection_name ASC`,
            [targetTable],
          )
        : await pgQuery<{
            collection_name: string;
            record_id: string;
            payload: any;
            synced_at?: string;
          }>(
            `SELECT collection_name, record_id, payload, synced_at::text as synced_at FROM public.erp_sync_records ORDER BY collection_name ASC`,
          );
      allRecords.push(...pgRes.rows);
    }

    if (allRecords.length === 0) {
      return {
        success: true,
        totalRestoredRows: 0,
        tablesRestored: 0,
        details: [],
      };
    }

    const { totalRestoredRows, details } =
      applyInboundPostgresRecordsToSqliteWal(allRecords);

    totalRehydratedRecords += totalRestoredRows;
    lastRehydratedAt = new Date().toISOString();
    lastDeltaSyncedAt = lastRehydratedAt;

    return {
      success: true,
      totalRestoredRows,
      tablesRestored: details.length,
      details,
    };
  } catch (err: any) {
    return {
      success: false,
      totalRestoredRows: 0,
      tablesRestored: 0,
      details: [],
      error: err?.message || String(err),
    };
  }
}

/**
 * Incremental Delta Sync from PostgreSQL Primary SSOT -> SQLite WAL Secondary Cache.
 * Fetches only records modified in PostgreSQL since `last_delta_watermark` (`synced_at > watermark`)
 * and applies them into the in-process SQLite WAL cache.
 */
export async function pullPostgresDeltasToSqlite(): Promise<{
  success: boolean;
  pulledRows: number;
  tablesUpdated: number;
  watermark: string | null;
  details: Array<{ table: string; restored: number }>;
  error?: string;
}> {
  if (isDeltaPulling) {
    return {
      success: true,
      pulledRows: 0,
      tablesUpdated: 0,
      watermark: getHybridSyncWatermark(sqliteDb),
      details: [],
    };
  }

  isDeltaPulling = true;
  try {
    const currentWatermark = getHybridSyncWatermark(sqliteDb);
    const deltaRecords: Array<{
      collection_name: string;
      record_id: string;
      payload: any;
      synced_at?: string;
    }> = [];

    let usedDirectFallback = !SUPABASE_SERVICE_ROLE_KEY && isDirectPgConnected();

    if (!usedDirectFallback) {
      let query = supabaseServerClient
        .from("erp_sync_records")
        .select("collection_name, record_id, payload, synced_at")
        .order("synced_at", { ascending: true })
        .limit(500);

      if (currentWatermark) {
        query = query.gt("synced_at", currentWatermark);
      }

      const { data, error } = await query;
      if (error) {
        if (isDirectPgConnected()) {
          usedDirectFallback = true;
        } else {
          return {
            success: false,
            pulledRows: 0,
            tablesUpdated: 0,
            watermark: currentWatermark,
            details: [],
            error: error.message,
          };
        }
      } else if (data && data.length > 0) {
        deltaRecords.push(...data);
      }
    }

    if (usedDirectFallback && isDirectPgConnected()) {
      const pgRes = currentWatermark
        ? await pgQuery<{
            collection_name: string;
            record_id: string;
            payload: any;
            synced_at?: string;
          }>(
            `SELECT collection_name, record_id, payload, synced_at::text as synced_at
             FROM public.erp_sync_records
             WHERE synced_at > $1::timestamptz
             ORDER BY synced_at ASC
             LIMIT 500`,
            [currentWatermark],
          )
        : await pgQuery<{
            collection_name: string;
            record_id: string;
            payload: any;
            synced_at?: string;
          }>(
            `SELECT collection_name, record_id, payload, synced_at::text as synced_at
             FROM public.erp_sync_records
             ORDER BY synced_at ASC
             LIMIT 500`,
          );
      deltaRecords.push(...pgRes.rows);
    }

    lastDeltaSyncedAt = new Date().toISOString();

    if (deltaRecords.length === 0) {
      return {
        success: true,
        pulledRows: 0,
        tablesUpdated: 0,
        watermark: currentWatermark,
        details: [],
      };
    }

    const { totalRestoredRows, details, maxSyncedAt } =
      applyInboundPostgresRecordsToSqliteWal(deltaRecords);

    totalDeltaPulledRecords += totalRestoredRows;

    return {
      success: true,
      pulledRows: totalRestoredRows,
      tablesUpdated: details.length,
      watermark: maxSyncedAt || currentWatermark,
      details,
    };
  } catch (err: any) {
    return {
      success: false,
      pulledRows: 0,
      tablesUpdated: 0,
      watermark: getHybridSyncWatermark(sqliteDb),
      details: [],
      error: err?.message || String(err),
    };
  } finally {
    isDeltaPulling = false;
  }
}

export function startPostgresDeltaSyncWorker(intervalMs = 15000) {
  if (deltaWorkerTimer) return;
  deltaWorkerTimer = setInterval(() => {
    pullPostgresDeltasToSqlite().catch(() => {
      // non-blocking background delta poll
    });
  }, intervalMs);
}

