/**
 * Inspects live PostgreSQL Primary SSOT connection & table readiness (`todos` and `erp_sync_records`)
 * alongside SQLite WAL Secondary Cache telemetry.
 */
export async function getSupabaseServerStatus() {
  const start = Date.now();
  try {
    let todosReady = false;
    let todosCount = 0;
    let todosRows: any[] = [];
    let todosError: string | null = null;

    const todosRes = await supabaseServerClient
      .from("todos")
      .select("*", { count: "exact" })
      .order("id", { ascending: true })
      .limit(25);

    if (!todosRes.error) {
      todosReady = true;
      todosCount = todosRes.count ?? (todosRes.data?.length || 0);
      todosRows = todosRes.data || [];
    } else if (isDirectPgConnected()) {
      const pgTodos = await pgQuery(
        `SELECT id, name, is_complete, created_at FROM public.todos ORDER BY id ASC LIMIT 25`,
      );
      const pgCount = await pgQuery<{ count: string }>(
        `SELECT COUNT(*)::text as count FROM public.todos`,
      );
      todosReady = true;
      todosRows = pgTodos.rows;
      todosCount = parseInt(pgCount.rows[0]?.count || "0", 10);
    } else {
      todosError = todosRes.error.message;
    }

    let erpSyncReady = false;
    let erpSyncCount = 0;
    let erpSyncRecent: any[] = [];
    let erpSyncError: string | null = null;
    let activeErpPolicies: Array<{ policyname: string; roles: string[] }> = [];

    if (isDirectPgConnected()) {
      const pgErp = await pgQuery(
        `SELECT collection_name, record_id, synced_at FROM public.erp_sync_records ORDER BY synced_at DESC LIMIT 15`,
      );
      const pgErpCount = await pgQuery<{ count: string }>(
        `SELECT COUNT(*)::text as count FROM public.erp_sync_records`,
      );
      erpSyncReady = true;
      erpSyncRecent = pgErp.rows;
      erpSyncCount = parseInt(pgErpCount.rows[0]?.count || "0", 10);

      try {
        const polRes = await pgQuery<{ policyname: string; roles: string[] }>(
          `SELECT policyname, roles::text[] as roles FROM pg_policies WHERE schemaname = 'public' AND tablename = 'erp_sync_records'`,
        );
        activeErpPolicies = polRes.rows || [];
        erpSyncRlsLockedToServiceRole =
          activeErpPolicies.length > 0 &&
          activeErpPolicies.every(
            (p) =>
              Array.isArray(p.roles) &&
              p.roles.length === 1 &&
              p.roles[0] === "service_role",
          );
      } catch {
        // Ignore pg_policies query error
      }
    } else {
      const erpSyncRes = await supabaseServerClient
        .from("erp_sync_records")
        .select("collection_name, record_id, synced_at", { count: "exact" })
        .order("synced_at", { ascending: false })
        .limit(15);

      if (!erpSyncRes.error) {
        erpSyncReady = true;
        erpSyncCount = erpSyncRes.count ?? (erpSyncRes.data?.length || 0);
        erpSyncRecent = erpSyncRes.data || [];
      } else {
        erpSyncError = erpSyncRes.error.message;
      }
    }

    const latencyMs = Date.now() - start;
    const pgInfo = getPgEngineInfo();

    return {
      connected: true,
      architecture:
        "ENTERPRISE HYBRID (PostgreSQL Primary SSOT + SQLite WAL Secondary Cache)",
      latencyMs,
      projectUrl: SUPABASE_URL,
      keyMode: SUPABASE_SERVICE_ROLE_KEY
        ? "SERVICE_ROLE"
        : pgInfo.directPgConnected
          ? "DIRECT_PG_POOL (RLS Service-Role Enforced)"
          : "PUBLISHABLE_KEY",
      hasServiceRoleKey: Boolean(SUPABASE_SERVICE_ROLE_KEY),
      directPgConnected: pgInfo.directPgConnected,
      schemaAutoInitialized: pgInfo.schemaAutoInitialized,
      publishableKeyMasked: SUPABASE_PUBLISHABLE_KEY
        ? `${SUPABASE_PUBLISHABLE_KEY.slice(0, 18)}...${SUPABASE_PUBLISHABLE_KEY.slice(-6)}`
        : "NOT_SET",
      todosTable: {
        exists: todosReady,
        rowCount: todosCount,
        rows: todosRows,
        error: todosError,
      },
      erpSyncTable: {
        exists: erpSyncReady,
        rowCount: erpSyncCount,
        recentRecords: erpSyncRecent,
        error: erpSyncError,
      },
      sqliteWal: getSqliteWalTelemetry(),
      securityHardening: getSecurityHardeningAudit(activeErpPolicies),
      bridgeStats: getPostgresBridgeStats(),
      sqlSetupScript: SUPABASE_SQL_SETUP_SCRIPT,
    };
  } catch (err: any) {
    return {
      connected: false,
      architecture:
        "ENTERPRISE HYBRID (PostgreSQL Primary SSOT + SQLite WAL Secondary Cache)",
      latencyMs: Date.now() - start,
      projectUrl: SUPABASE_URL,
      keyMode: SUPABASE_SERVICE_ROLE_KEY ? "SERVICE_ROLE" : "PUBLISHABLE_KEY",
      hasServiceRoleKey: Boolean(SUPABASE_SERVICE_ROLE_KEY),
      directPgConnected: isDirectPgConnected(),
      schemaAutoInitialized: false,
      error: err?.message || String(err),
      sqliteWal: getSqliteWalTelemetry(),
      securityHardening: getSecurityHardeningAudit(),
      bridgeStats: getPostgresBridgeStats(),
      sqlSetupScript: SUPABASE_SQL_SETUP_SCRIPT,
    };
  }
}
