/**
 * Enforces strict service_role-only RLS policy on public.erp_sync_records via DATABASE_URL
 */
export async function enforceServiceRoleRlsOnErpSync(): Promise<{
  success: boolean;
  lockedToServiceRole: boolean;
  policies: Array<{ policyname: string; roles: string[] }>;
  message: string;
}> {
  try {
    await getPgDb();
    if (!isDirectPgConnected()) {
      return {
        success: false,
        lockedToServiceRole: erpSyncRlsLockedToServiceRole,
        policies: [],
        message:
          "Koneksi langsung DATABASE_URL tidak aktif. Jalankan skrip SQL di Supabase SQL Editor.",
      };
    }

    await pgQuery(STRICT_ERP_SYNC_RLS_SQL);
    const polRes = await pgQuery<{ policyname: string; roles: string[] }>(
      `SELECT policyname, roles::text[] as roles FROM pg_policies WHERE schemaname = 'public' AND tablename = 'erp_sync_records'`,
    );

    const policies = polRes.rows || [];
    const onlyServiceRole =
      policies.length > 0 &&
      policies.every(
        (p) =>
          Array.isArray(p.roles) &&
          p.roles.length === 1 &&
          p.roles[0] === "service_role",
      );

    erpSyncRlsLockedToServiceRole = onlyServiceRole;
    return {
      success: true,
      lockedToServiceRole: onlyServiceRole,
      policies,
      message:
        "Kebijakan RLS pada public.erp_sync_records berhasil dikunci khusus untuk service_role (akses anon & authenticated dicabut).",
    };
  } catch (err: any) {
    return {
      success: false,
      lockedToServiceRole: false,
      policies: [],
      message: err?.message || String(err),
    };
  }
}

/**
 * Initializes the PostgreSQL connection and, if DATABASE_URL / SUPABASE_DB_URL is configured,
 * automatically provisions public.todos, public.erp_sync_records, and strict service_role RLS.
 */
export async function initPostgresDb(): Promise<boolean> {
  try {
    await getPgDb();
    if (isDirectPgConnected()) {
      await autoInitializeSupabaseSchemaViaPool(SUPABASE_SQL_SETUP_SCRIPT);
      await enforceServiceRoleRlsOnErpSync();
    }
    return true;
  } catch (err: any) {
    lastReplicationError = err?.message || String(err);
    console.error("[PostgresBridge] Initialization notice:", err);
    return false;
  }
}

